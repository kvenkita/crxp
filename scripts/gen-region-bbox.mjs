/**
 * Write netlify/region.mjs: the region's bounding box (from static/data/geo/counties.geojson, padded
 * by 0.05 degrees) used
 * by the geocode function to keep address suggestions inside the region. Runs in `npm run build`;
 * the output is committed so `netlify dev` works without a build.  node scripts/gen-region-bbox.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fcBbox, bboxRect, padBbox } from '../src/lib/geo/bbox.js';

// Small margin so addresses just inside the region edge still get suggestions.
const PAD_DEG = 0.05;

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fc = JSON.parse(fs.readFileSync(path.join(ROOT, 'static/data/geo/counties.geojson'), 'utf8'));
const rect = bboxRect(padBbox(fcBbox(fc), PAD_DEG));
const out = `// Generated by scripts/gen-region-bbox.mjs from static/data/geo/counties.geojson. Do not edit.\n` +
	`export const REGION_RECT = '${rect}'; // lon1,lat1,lon2,lat2\n`;
fs.writeFileSync(path.join(ROOT, 'netlify', 'region.mjs'), out);
console.log(`gen-region-bbox: ${rect}`);
